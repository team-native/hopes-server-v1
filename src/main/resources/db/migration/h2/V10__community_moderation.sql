-- 커뮤니티 신고 처리·운영자 권한.
-- 운영자는 API로 지정하지 않는다: UPDATE users SET account_role='ADMIN' WHERE email='...';
ALTER TABLE users ADD COLUMN account_role VARCHAR(20) DEFAULT 'USER' NOT NULL;

-- 운영자 숨김. 작성자 삭제(deleted)와 별개이며 복구할 수 있다.
ALTER TABLE community_posts ADD COLUMN hidden BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE community_comments ADD COLUMN hidden BOOLEAN DEFAULT FALSE NOT NULL;

-- 신고 처리 상태와 신고 시점 증거(작성자가 삭제·수정해도 남는다).
ALTER TABLE community_reports ADD COLUMN status VARCHAR(20) DEFAULT 'RECEIVED' NOT NULL;
ALTER TABLE community_reports ADD COLUMN target_post_id BIGINT;
ALTER TABLE community_reports ADD COLUMN snapshot_title VARCHAR(200);
ALTER TABLE community_reports ADD COLUMN snapshot_content VARCHAR(10000);
ALTER TABLE community_reports ADD COLUMN resolved_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE community_reports ADD COLUMN evidence_purged_at TIMESTAMP(6) WITH TIME ZONE;

-- 기존 신고는 지금 남아 있는 내용으로 증거를 채운다(이미 삭제된 대상은 비어 있다).
UPDATE community_reports SET
 target_post_id = target_id,
 snapshot_title = (SELECT p.title FROM community_posts p WHERE p.id = community_reports.target_id AND p.deleted = FALSE),
 snapshot_content = (SELECT p.content FROM community_posts p WHERE p.id = community_reports.target_id AND p.deleted = FALSE)
WHERE target_type = 'POST';
UPDATE community_reports SET
 target_post_id = (SELECT c.post_id FROM community_comments c WHERE c.id = community_reports.target_id),
 snapshot_content = (SELECT c.content FROM community_comments c WHERE c.id = community_reports.target_id AND c.deleted = FALSE)
WHERE target_type = 'COMMENT';

CREATE INDEX idx_community_reports_status ON community_reports(status,created_at,id);
CREATE INDEX idx_community_reports_target ON community_reports(target_type,target_id);

-- 처리 기록. 운영자 계정이 삭제돼도 기록은 남긴다(admin_id만 NULL).
CREATE TABLE community_moderation_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL, admin_id BIGINT,
 action VARCHAR(20) NOT NULL, memo VARCHAR(2000) NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 FOREIGN KEY(report_id) REFERENCES community_reports(id) ON DELETE CASCADE,
 FOREIGN KEY(admin_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_moderation_actions_report ON community_moderation_actions(report_id,created_at,id);

-- 제재. 제재 대상 계정이 삭제되면 함께 삭제한다.
CREATE TABLE community_sanctions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, report_id BIGINT,
 sanction_type VARCHAR(20) NOT NULL, reason VARCHAR(2000) NOT NULL,
 starts_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, ends_at TIMESTAMP(6) WITH TIME ZONE,
 created_by BIGINT, created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(report_id) REFERENCES community_reports(id) ON DELETE SET NULL,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_community_sanctions_user ON community_sanctions(user_id,sanction_type,ends_at);
