CREATE TABLE community_boards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, cohort INTEGER UNIQUE, sort_order INTEGER NOT NULL
);
